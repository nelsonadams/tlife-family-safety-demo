"""Turn raw OSRM routes (tools/routes.raw.json) into data/routes.js with demo speed profiles."""
import json, random, math, os
random.seed(7)
here = os.path.dirname(__file__)
raw = json.load(open(os.path.join(here, "routes.raw.json")))

def smooth(v, k=4):
    return [round(sum(v[max(0, i-k):i+k+1]) / len(v[max(0, i-k):i+k+1]), 1) for i in range(len(v))]

out = {}
for name, r in raw.items():
    mph = r["mph"]
    if name == "ride":
        mph = [m * 1.5 if m > 40 else m * 1.15 for m in mph]
        mph = [max(m, 12) for m in mph]
        mph = smooth(mph, 6)
    else:
        mph = smooth([3.1 + random.uniform(-0.4, 0.4) for _ in mph], 2)
    out[name] = {"coords": r["coords"], "mph": mph}

os.makedirs(os.path.join(here, "..", "data"), exist_ok=True)
with open(os.path.join(here, "..", "data", "routes.js"), "w") as f:
    f.write("// Generated by tools/build_routes.py from OSRM road geometry (© OpenStreetMap contributors).\n")
    f.write("window.DEMO_ROUTES = " + json.dumps(out, separators=(",", ":")) + ";\n")
for k, v in out.items():
    print(k, "max mph", max(v["mph"]))
